    $searchLower = strtolower($search);

    $filtered = array_filter(
        $openAccessCountry,
        static function (array $row) use ($searchLower): bool {

            if (
                str_contains(
                    strtolower((string) $row['country']),
                    $searchLower
                )
            ) {
                return true;
            }

            for ($year = 2010; $year <= 2019; $year++) {

                if (
                    str_contains(
                        strtolower((string) $row[(string) $year]),
                        $searchLower
                    )
                ) {
                    return true;
                }
            }

            return false;
        }
    );

    $filtered = array_values($filtered);
}

